def seed_default_questions(test=None):
    """Seed the predefined question bank into the database.

    If a test instance is provided, questions are attached to that test.
    Returns a tuple of (created_count, existing_count).
    """
    from hr.models import AptitudeQuestion

    created_count = 0
    existing_count = 0

    for q_data in PREDEFINED_QUESTIONS:
        query_kwargs = {
            "question": q_data["question"],
        }
        if test is not None:
            query_kwargs["test"] = test

        question_obj, created = AptitudeQuestion.objects.get_or_create(
            **query_kwargs,
            defaults={
                "category": q_data["category"],
                "option_a": q_data["option_a"],
                "option_b": q_data["option_b"],
                "option_c": q_data["option_c"],
                "option_d": q_data["option_d"],
                "correct_answer": q_data["correct_answer"],
                "is_active": True,
                "test": test,
            },
        )
        if created:
            created_count += 1
        else:
            # Update fields if category or options were missing
            updated = False
            if question_obj.category != q_data["category"]:
                question_obj.category = q_data["category"]
                updated = True
            if not question_obj.is_active:
                question_obj.is_active = True
                updated = True
            if updated:
                question_obj.save()
            existing_count += 1

    return created_count, existing_count

